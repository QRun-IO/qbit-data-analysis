package com.kingsrook.qbits.dataanalysis;


import java.util.ArrayList;
import java.util.List;
import com.kingsrook.qbits.dataanalysis.model.DataAnalysisTables;
import com.kingsrook.qqq.backend.core.model.metadata.fields.QFieldMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.UniqueKey;


/*******************************************************************************
 ** PostgreSQL DDL generated from the same tables and unique keys used by QQQ.
 *******************************************************************************/
public final class DataAnalysisSchema
{
   /*******************************************************************************
    ** Utility class.
    *******************************************************************************/
   private DataAnalysisSchema()
   {
   }



   /*******************************************************************************
    ** Idempotent table and unique index creation; hosts own migration execution.
    *******************************************************************************/
   public static String postgresScript(DataAnalysisQBitConfig config)
   {
      List<String> statements = new ArrayList<>();
      for(QTableMetaData table : DataAnalysisTables.tables(config))
      {
         List<String> columns = new ArrayList<>();
         for(QFieldMetaData field : table.getFields().values())
         {
            columns.add("   " + field.getBackendName() + " " + ("id".equals(field.getName())
               ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : sqlType(field) + (Boolean.TRUE.equals(field.getIsRequired()) ? " NOT NULL" : "")));
         }
         statements.add("CREATE TABLE IF NOT EXISTS " + table.getName() + " (\n" + String.join(",\n", columns) + "\n)");
         if(table.getUniqueKeys() != null)
         {
            int index = 0;
            for(UniqueKey key : table.getUniqueKeys())
            {
               index++;
               statements.add("CREATE UNIQUE INDEX IF NOT EXISTS uq_" + table.getName() + "_" + index + " ON " + table.getName()
                  + " (" + String.join(", ", key.getFieldNames().stream().map(name -> table.getField(name).getBackendName()).toList()) + ")");
            }
         }
      }
      return (String.join(";\n", statements) + ";\n");
   }



   /*******************************************************************************
    ** PostgreSQL types for the table metadata.
    *******************************************************************************/
   private static String sqlType(QFieldMetaData field)
   {
      return (switch(field.getType())
      {
         case INTEGER -> "INTEGER";
         case LONG -> "BIGINT";
         case DECIMAL -> "NUMERIC";
         case BOOLEAN -> "BOOLEAN";
         case DATE_TIME -> "TIMESTAMP WITHOUT TIME ZONE";
         case TEXT -> "TEXT";
         default -> "VARCHAR(" + field.getMaxLength() + ")";
      });
   }
}
